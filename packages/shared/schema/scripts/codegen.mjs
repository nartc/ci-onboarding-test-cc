// Generates TypeScript types and guards from schemas/*.json into src/generated.
import { mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { basename, dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const schemaDir = join(root, 'schemas');
const outDir = join(root, 'src', 'generated');

rmSync(outDir, { recursive: true, force: true });
mkdirSync(outDir, { recursive: true });

const files = readdirSync(schemaDir)
  .filter((f) => f.endsWith('.json'))
  .sort();
const barrel = [];

for (const file of files) {
  const { name, fields } = JSON.parse(readFileSync(join(schemaDir, file), 'utf8'));
  const id = basename(file, '.json');
  const entries = Object.entries(fields);
  const lines = [
    '// Generated by scripts/codegen.mjs. Do not edit.',
    `export interface ${name} {`,
    ...entries.map(([k, t]) => `  readonly ${k}: ${t};`),
    '}',
    '',
    `export const ${id}Fields = ${JSON.stringify(entries.map(([k]) => k))} as const;`,
    '',
    `export function is${name}(value: unknown): value is ${name} {`,
    "  if (typeof value !== 'object' || value === null) return false;",
    '  const v = value as Record<string, unknown>;',
    `  return ${entries.map(([k, t]) => `typeof v['${k}'] === '${t}'`).join(' && ')};`,
    '}',
    '',
  ];
  writeFileSync(join(outDir, `${id}.ts`), lines.join('\n'));
  barrel.push(`export * from './${id}.js';`);
}

writeFileSync(
  join(outDir, 'index.ts'),
  ['// Generated by scripts/codegen.mjs. Do not edit.', ...barrel, ''].join('\n'),
);
console.log(`codegen: wrote ${files.length} schemas to src/generated`);
