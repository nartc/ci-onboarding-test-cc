// codegen for the "slow" lab modules: writes many small, type-heavy files into src/generated,
// so build and typecheck have real work to do. Usage: node emit-parts.mjs <count>
import { mkdirSync, rmSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const count = Number(process.argv[2] ?? 100);
const outDir = join(process.cwd(), 'src', 'generated');
rmSync(outDir, { recursive: true, force: true });
mkdirSync(outDir, { recursive: true });

const id = (i) => String(i).padStart(3, '0');

for (let i = 1; i <= count; i++) {
  const prev = i > 1 ? id(i - 1) : null;
  const fields = Array.from(
    { length: 12 },
    (_, f) => `  readonly f${f}: ${f % 3 === 0 ? 'string' : f % 3 === 1 ? 'number' : 'boolean'};`,
  );
  const lines = [
    '// Generated by tools/lab/emit-parts.mjs. Do not edit.',
    prev ? `import type { Part${prev} } from './part-${prev}.js';` : '',
    '',
    `export type Shape${id(i)} = {`,
    ...fields,
    '};',
    '',
    `export interface Part${id(i)}<T extends Record<string, unknown> = Shape${id(i)}> {`,
    `  readonly id: ${i};`,
    '  readonly value: T;',
    prev ? `  readonly previous?: Part${prev}<T>;` : '',
    '}',
    '',
    `export type Renamed${id(i)}<T> = {`,
    `  [K in keyof T as \`p${i}_\${string & K}\`]: T[K] extends string ? number : T[K] extends number ? string : T[K];`,
    '};',
    '',
    `export type Deep${id(i)}<T> = T extends object ? { readonly [K in keyof T]: Deep${id(i)}<T[K]> } : T;`,
    '',
    `export function part${id(i)}<T extends Record<string, unknown>>(value: T): Part${id(i)}<T> {`,
    `  return { id: ${i}, value };`,
    '}',
    '',
    `export const table${id(i)} = {`,
    ...Array.from(
      { length: 20 },
      (_, k) => `  k${k}: { index: ${k}, label: 'part ${i} key ${k}', even: ${k % 2 === 0} },`,
    ),
    '} as const;',
    '',
    `export type Table${id(i)}Key = keyof typeof table${id(i)};`,
    '',
  ];
  writeFileSync(
    join(outDir, `part-${id(i)}.ts`),
    lines.filter((l, n) => l !== '' || lines[n - 1] !== '').join('\n'),
  );
}

const barrel = [
  '// Generated by tools/lab/emit-parts.mjs. Do not edit.',
  ...Array.from({ length: count }, (_, i) => `export * from './part-${id(i + 1)}.js';`),
  `export const partCount = ${count};`,
  '',
];
writeFileSync(join(outDir, 'index.ts'), barrel.join('\n'));
console.log(`emit-parts: wrote ${count} parts to src/generated`);
